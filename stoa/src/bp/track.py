"""The experiment registry. Each run is a directory. The ledger is generated from the directories."""

from __future__ import annotations

import json
import platform
import subprocess
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any

from bp.contract import Frozen
from bp.paths import LEDGER, RUNS, STOA
from bp.session import ItemResult
from bp.stats import Summary

if TYPE_CHECKING:
    from pathlib import Path


class Meta(Frozen):
    run_id: str
    solver: str
    suite: str
    suite_hash: str
    selector: dict[str, Any]
    note: str
    sealed: bool
    jobs: int
    git_sha: str
    git_dirty: bool
    started: str
    seconds: float
    host: str


def _git(*args: str) -> str:
    done = subprocess.run(["git", *args], cwd=STOA, capture_output=True, text=True, check=False)
    return done.stdout.strip()


def git_state() -> tuple[str, bool]:
    return _git("rev-parse", "--short", "HEAD"), bool(_git("status", "--porcelain", "--", "src", "pyproject.toml"))


def new_run_id(solver: str, suite: str) -> tuple[str, str]:
    now = datetime.now(UTC)
    safe = solver.replace(":", ".").replace("/", "-")
    short = safe.rsplit(".", 1)[-1]
    return f"{now:%Y%m%d-%H%M%S}-{now.microsecond // 1000:03d}-{short}-{suite}", now.isoformat(timespec="seconds")


def save_run(meta: Meta, summary: Summary, results: list[ItemResult]) -> Path:
    directory = RUNS / meta.run_id
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "meta.json").write_text(meta.model_dump_json(indent=1) + "\n")
    (directory / "summary.json").write_text(summary.model_dump_json(indent=1) + "\n")
    with (directory / "items.jsonl").open("w", encoding="utf-8") as handle:
        for result in results:
            handle.write(result.model_dump_json() + "\n")
    return directory


def load_results(run_id: str) -> list[ItemResult]:
    with (RUNS / run_id / "items.jsonl").open(encoding="utf-8") as handle:
        return [ItemResult.model_validate_json(line) for line in handle if line.strip()]


def host() -> str:
    return platform.node().split(".")[0]


def _percent(value: float | None) -> str:
    return "-" if value is None else f"{100 * value:.2f}"


def write_ledger() -> int:
    """Write experiments/LEDGER.md from every run directory. It returns the number of runs."""
    rows: list[tuple[str, str]] = []
    for directory in sorted(RUNS.glob("*/")):
        meta_path, summary_path = directory / "meta.json", directory / "summary.json"
        if not (meta_path.exists() and summary_path.exists()):
            continue
        meta = Meta.model_validate_json(meta_path.read_text())
        s = Summary.model_validate_json(summary_path.read_text())
        selector = " ".join(f"{k}={v}" for k, v in sorted(meta.selector.items()) if v) or "all"
        rows.append(
            (
                meta.started,
                f"| `{meta.run_id}` | {meta.solver} | {meta.suite} ({selector}) | {s.items} | "
                f"{s.score.value:+.3f} [{s.score.low:+.3f}, {s.score.high:+.3f}] | {_percent(s.accuracy.value)} | "
                f"{_percent(s.row_accuracy)} | {_percent(s.answered)} | {_percent(s.wrong)} | "
                f"{_percent(s.selective_accuracy)} | {s.cost_usd:.2f} | {s.latency_p50_ms:.0f} | "
                f"{'yes' if meta.sealed else 'NO'} | {meta.git_sha}{'*' if meta.git_dirty else ''} | {meta.note} |",
            )
        )
    rows.sort()
    head = [
        "# Experiment ledger",
        "",
        "Generated by `uv run bp ledger`. Do not edit. One row for each run in `experiments/runs/`.",
        "",
        "- Score: +1 right, 0 abstained, -1 wrong, mean over items, with a 95% cluster bootstrap interval.",
        "- Acc: items right, percent. An item with translations is right only when every translation is right.",
        "- Row acc: public question rows right, percent. This is the number that Stoa's own rule gives.",
        "- Sel acc: accuracy on the items that the solver answered.",
        "- Sealed: the solver ran in a sandbox that cannot read keys, labels or original file names.",
        "- A `*` after the commit means that the code had changes that were not committed.",
        "",
        "| Run | Solver | Suite | Items | Score | Acc % | Row acc % | Answered % | Wrong % | Sel acc % | Cost $ | p50 ms | Sealed | Commit | Note |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text("\n".join(head + [row for _, row in rows]) + "\n")
    return len(rows)


def dump(obj: object) -> str:
    return json.dumps(obj, indent=1, ensure_ascii=False)
